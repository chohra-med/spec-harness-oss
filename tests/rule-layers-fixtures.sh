# Schema 4 rule layers: the generated stack, curated packs, readable one-line rules, one home per
# fact. One READY fixture, then one planted fault per check, each restored before the next.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd -P)"
# shellcheck source=lib/portable.sh
. "$ROOT/tests/lib/portable.sh"
require_tools git
require_python311
