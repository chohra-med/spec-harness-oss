python3 -I -B - "$ROOT" "$TMP" <<'PY'
import copy
import hashlib
import json
import subprocess
import sys
from pathlib import Path

root = Path(sys.argv[1])
target = Path(sys.argv[2]) / "app"
index = root / "bin/sh-index.sh"
bind = root / "bin/sh-gen-agents.sh"
stack_cli = [str(root / "bin/spec-harness"), "stack"]
packs = root / "templates/rule-packs"

def run(args, expected, label):
    result = subprocess.run(args, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if result.returncode != expected:
        raise AssertionError(f"{label}: expected exit {expected}, got {result.returncode}\n{result.stdout}")
    return result.stdout

def write(rel, content):
    path = target / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content)

def read(rel):
    return (target / rel).read_text()

def sha(rel):
    return hashlib.sha256((target / rel).read_bytes()).hexdigest()

# Every shipped pack parses as readable rule lines with a URL source, and no ID repeats across packs.
sys.path.insert(0, str(root / "bin"))
import sh_rule_layers
seen = {}
for pack in sorted(packs.glob("*.md")):
    if pack.stem == "README":
        continue
    text = pack.read_text()
    rules, defects = sh_rule_layers.parse(text)
    assert rules and not defects, (pack.name, defects)
    assert f"<!-- pack: {pack.stem} -->" in text and sh_rule_layers.LAYER.search(text), pack.name
    assert not pack.stem.startswith("tool-") or sh_rule_layers.APPLIES.search(text), f"{pack.name}: tool pack without applies"
    for rule in rules:
        assert "https://" in rule["source"], (pack.name, rule["id"])
        assert rule["id"] not in seen, f"{rule['id']} in {pack.name} and {seen.get(rule['id'])}"
        seen[rule["id"]] = pack.name
print(f"PASS: {len(seen)} rules in the shipped packs are readable, sourced and uniquely numbered")

# A small Expo app with a lockfile, one policy file and one source file.
write("package.json", json.dumps({"name": "layers-fixture", "scripts": {"test": "jest"}, "dependencies": {
    "expo": "~57.0.27", "react-native": "0.86.3", "@sentry/react-native": "~7.11.0"}}, indent=2) + "\n")
def lockfile(expo_version):
    return json.dumps({"name": "layers-fixture", "lockfileVersion": 3, "packages": {
        "": {"name": "layers-fixture"},
        "node_modules/expo": {"version": expo_version},
        "node_modules/react-native": {"version": "0.86.3"},
        "node_modules/@sentry/react-native": {"version": "7.11.0"}}}, indent=2) + "\n"
write("package-lock.json", lockfile("57.0.27"))
write("src/App.tsx", "import * as Sentry from '@sentry/react-native';\n\nexport function App() {\n  Sentry.captureMessage('start');\n  return null;\n}\n")
write("CONTRIBUTING.md", "# Contributing\n- Report errors through the shared Sentry module only.\n")
# A project-owned context map makes index write the structured inventory the drift check reads.
write("ai_rules/context_map.md", "# Team map\nKept byte for byte.\n")

# A user-owned stack.md is preserved; the generated one is written and checked.
write("ai_rules/stack.md", "# My notes\n")
out = run(stack_cli + [str(target)], 1, "stack refuses a user-owned file")
assert "not generated by Spec Harness; preserved" in out and read("ai_rules/stack.md") == "# My notes\n", out
(target / "ai_rules/stack.md").unlink()
run(["bash", str(index), str(target)], 0, "first index")
assert "WROTE: ai_rules/stack.md" in run(stack_cli + [str(target)], 0, "stack write")
stack_text = read("ai_rules/stack.md")
assert "| `expo` | `~57.0.27` | `57.0.27` | dependency |" in stack_text, stack_text
assert "READY:" in run(stack_cli + [str(target), "--check"], 0, "stack check GREEN")
print("PASS: stack.md is generated from package.json and package-lock.json, and a user-owned file is preserved")

inventory = json.loads(read("ai_rules/project_inventory.json"))
source = next(row for row in inventory["packages"][0]["representative_sources"] if row["read_status"] == "read")
assert source["path"] == "src/App.tsx", source
assert all(row["path"] != "ai_rules/stack.md" for row in inventory["rule_files"]), "stack.md must not be indexed as policy"
citation = {"package_path": ".", "path": "src/App.tsx", "line_start": 1, "line_end": 4, "sha256": sha("src/App.tsx")}
cited = "src/App.tsx:1-4"
HASH = sha("ai_rules/project_inventory.json")
bound = lambda: f"<!-- source-bound: inventory-sha256={HASH} -->"

# Rule modules: every baseline pack and the tool packs that match the stack, copied byte for byte.
modules = []
def add_module(name, text):
    rel = f"ai_rules/rules/{name}.md"
    write(rel, text)
    modules.append({"name": name, "path": rel, "sha256": "", "citations": [citation]})
for pack in sorted(packs.glob("*.md")):
    if pack.stem == "README" or pack.stem in ("tool-expo-router", "tool-tanstack-query", "standard-owasp-masvs"):
        continue
    commitment = "<!-- commitment: STD-01 -->\n" if pack.stem.startswith("standard-") else ""
    add_module(pack.stem, pack.read_text() + f"\n{commitment}Applies here: {cited}\n" + bound() + "\n")
add_module("project-errors", "# Project rules: errors\n\n<!-- rule-layer: project -->\n\n"
           "- **PROJ-01** Report every caught error through the shared Sentry module, never by calling the SDK directly. (source: CONTRIBUTING.md, line 2; " + cited + ")\n\n"
           + bound() + "\n")
write("RULES.md", "# Rules for .\n\n"
      "## Coding\n- **CODE-01** Keep each screen component in its own file under src. (source: observed in " + cited + ")\n\n"
      "## Architecture\n- [errors](ai_rules/rules/project-errors.md)\n\n"
      "## Packages\n- Versions: [stack](ai_rules/stack.md)\n\n"
      "## Testing\n- **TESTRUN-01** Run the jest script before handing over a change. (source: package.json scripts)\n\n"
      "## Reviewing\n- Baseline: " + ", ".join(f"[{m['name']}]({m['path']})" for m in modules if m["name"] != "project-errors") + "\n")
write(".memory/10-product.md", "# 10-product\n\n## Standards and compliance\n\n"
      "- **STD-01** The app meets the European Accessibility Act through EN 301 549. (source: product owner, 2026-10-21, status: required)\n\n## Domain rules\n\n- **BIZ-01** Never show a price before the customer's country is known. (source: product owner, 2026-10-21)\n")
write(".memory/60-decisions.md", "# 60-decisions\n\n- **DEC-001** Use the shared Sentry module as the only error reporting entry point. (source: tech lead, 2026-10-21)\n")

skills = []
for name in ("spec-harness-architecture", "spec-harness-performance", "spec-harness-packages", "spec-harness-quality", "spec-harness-conduct"):
    rel = f".claude/skills/{name}/SKILL.md"
    write(rel, f"# {name}\n\nPackage applicability: .\n\nApplies PROJ-01 and SEC-04; versions in ai_rules/stack.md.\n\n{bound()}\nEvidence: {cited}\n")
    skills.append({"name": name, "status": "READY", "path": rel, "sha256": "", "package_paths": ["."], "citations": [citation]})
roles = []
for name in ("sdd-planner", "sdd-implementer", "sdd-tester", "sdd-verifier", "sdd-reviewer"):
    rel = f".claude/agents/{name}.md"
    write(rel, "\n".join(["<!-- GEN:rules START -->", "Package: .", f"Enforce PROJ-01, SENTRY-01 and the baseline modules. Evidence {cited}.",
                          "Run in a fresh context.", f"<!-- bound: 2026-10-21 inventory-sha256={HASH} -->", "<!-- GEN:rules END -->"]) + "\n")
    roles.append({"name": name, "status": "BOUND", "path": rel, "sha256": "", "package_paths": ["."], "citations": [citation],
                  "selection_reason": "Required role."})

receipt = {
    "format": "spec-harness-synthesis", "schema_version": 4, "status": "READY",
    "inventory_path": "ai_rules/project_inventory.json", "inventory_sha256": HASH, "package_paths": ["."],
    "packages": [{"path": ".", "status": "READY", "rules_path": "RULES.md", "sha256": "", "citations": [citation], "rule_modules": modules}],
    "skills": skills, "roles": roles,
    "excluded_roles": [{"name": "sdd-design-verifier", "reason": "No visual surface in this fixture."}],
    "pending_reasons": [],
    "policy_sources": [{"path": "CONTRIBUTING.md", "sha256": sha("CONTRIBUTING.md"), "requirement_ids": ["CONTRIB-1"]}],
    "policy_coverage": [{"id": "CONTRIB-1", "path": "CONTRIBUTING.md", "sha256": sha("CONTRIBUTING.md"), "line_start": 2, "line_end": 2,
                         "disposition": "captured", "rule_path": "ai_rules/rules/project-errors.md", "rule_anchor": "PROJ-01"}],
    "stack": {"path": "ai_rules/stack.md", "sha256": ""},
    "excluded_packs": [], "rule_conflicts": [],
}
# Fixture outputs mention the RULES.md citation only through the code rule; the checker wants it.
RECEIPT = ".claude/agents/.init-synthesis.json"

def rehash(value):
    package = value["packages"][0]
    package["sha256"] = sha("RULES.md")
    for row in package.get("rule_modules", []) + value["skills"] + value["roles"]:
        row["sha256"] = sha(row["path"])
    if isinstance(value.get("stack"), dict):
        value["stack"]["sha256"] = sha("ai_rules/stack.md")
    return value

def save(value):
    write(RECEIPT, json.dumps(rehash(value), indent=2) + "\n")

# Write the receipt so the index sees the rule outputs as receipt-owned, reindex, then move every
# marker consumer to the new inventory hash.
save(receipt)
run(["bash", str(index), str(target)], 0, "reindex with receipt-owned outputs")
old, HASH = HASH, sha("ai_rules/project_inventory.json")
for row in modules + skills + roles:
    write(row["path"], read(row["path"]).replace(old, HASH))
receipt["inventory_sha256"] = HASH
save(receipt)
green = run(["bash", str(bind), "--check", str(target)], 0, "schema 4 GREEN control")
assert "READY: 1 package, 5 skills, 5 selected roles" in green, green
run(["bash", str(index), str(target)], 0, "reindex fixed point")
assert sha("ai_rules/project_inventory.json") == HASH, "reindex changed the inventory: stack.md or a module is not stable"
print("PASS: schema 4 fixture with stack, packs, project, business and decision layers is READY; reindex is a fixed point")

def check_red(label, needle, mutate_files=None, mutate_receipt=None):
    saved = {rel: (target / rel).read_bytes() for rel in [RECEIPT, "RULES.md", "package.json", "package-lock.json", "ai_rules/stack.md",
                                                           ".memory/10-product.md", ".memory/60-decisions.md"]
             + [row["path"] for row in modules + skills + roles]}
    try:
        value = copy.deepcopy(receipt)
        if mutate_files:
            mutate_files()
        if mutate_receipt:
            mutate_receipt(value)
        save(value)
        output = run(["bash", str(bind), "--check", str(target)], 1, label)
        assert needle in output, (label, needle, output)
        print(f"RED control observed: {label} -> {needle}")
    finally:
        for rel, data in saved.items():
            (target / rel).write_bytes(data)

def append(rel, text):
    return lambda: write(rel, read(rel) + text)

PROJ = "ai_rules/rules/project-errors.md"
check_red("pointer line", "is a pointer, not a rule",
          append(PROJ, "- POLICY: Apply the canonical package requirements from CONVENTIONS.md. Coverage IDs: policy-266.\n"))
check_red("unreadable rule", "is not one readable sentence", append(PROJ, "- **PROJ-02** Errors (source: x)\n"))
check_red("rule-like line without a source tag", "is not a readable rule line", append(PROJ, "- **PROJ-03** Keep errors in one module.\n"))
check_red("duplicate rule ID", "rule ID PROJ-01 is defined twice", append("RULES.md", "- **PROJ-01** Name test files after the screen they cover. (source: observed)\n"))
check_red("same words twice", "say the same thing",
          append("RULES.md", "- **CODE-02** Report every caught error through the shared Sentry module, never by calling the SDK directly. (source: observed)\n"))
check_red("proposed convention", "is PROPOSED", append(PROJ, "- **PROJ-04** Put every hook in a hooks folder next to its screen. (source: observed, PROPOSED)\n"))
check_red("version in a skill", "names a version of expo", append(".claude/skills/spec-harness-packages/SKILL.md", "Use the APIs that ship with 57.0.27 only.\n"))
check_red("exact version in a rule", "names a version of react-native",
          append("RULES.md", "- **CODE-03** Use the bridgeless APIs that ship with 0.86.3 only. (source: observed)\n"))
check_red("rule copied into a role block", "copies rule PROJ-01",
          lambda: write(".claude/agents/sdd-reviewer.md", read(".claude/agents/sdd-reviewer.md").replace(
              "Run in a fresh context.", "Run in a fresh context. Report every caught error through the shared Sentry module, never by calling the SDK directly.")))
def reword_pack():
    rel = "ai_rules/rules/baseline-security.md"
    write(rel, read(rel).replace("Never commit a secret", "Do not commit a secret"))
check_red("reworded pack rule", "differs from pack baseline-security", reword_pack)
def drop_layer():
    write(PROJ, read(PROJ).replace("<!-- rule-layer: project -->", ""))
check_red("module without a layer", "needs <!-- rule-layer", drop_layer)
check_red("lower layer overrides higher", "cannot override DEC-001",
          append(PROJ, "- **PROJ-05** Call the Sentry SDK directly from screens that need breadcrumbs. (source: observed, overrides DEC-001)\n"))
check_red("override of an undefined rule", "overrides NOPE-01, which is not defined",
          append(".memory/60-decisions.md", "- **DEC-002** Keep one shared error reporting module for the whole app. (source: tech lead, overrides NOPE-01)\n"))
def stale_stack():
    write("package.json", read("package.json").replace("~57.0.27", "~57.0.28"))
check_red("stale stack", "is missing or stale against the manifests", stale_stack)
def old_expo():
    write("package.json", read("package.json").replace("~57.0.27", "~49.0.0"))
    write("package-lock.json", lockfile("49.0.0"))
    run(stack_cli + [str(target)], 0, "regenerate stack for an old SDK")
check_red("tool module outside its version range", "outside this module's range >=50", old_expo)
def drop_module(name):
    def mutate(value):
        package = value["packages"][0]
        package["rule_modules"] = [row for row in package["rule_modules"] if row["name"] != name]
        write("RULES.md", read("RULES.md").replace(f"[{name}](ai_rules/rules/{name}.md)", name))
    return mutate
check_red("open rule conflict", "rule conflict SEC-04 vs DEC-001 is open",
          mutate_receipt=lambda v: v.__setitem__("rule_conflicts", [{"ids": ["SEC-04", "DEC-001"], "status": "open"}]))
check_red("ledger anchored to free text", "must anchor to a rule ID",
          mutate_receipt=lambda v: v["policy_coverage"][0].__setitem__("rule_anchor", "Report every caught error"))
check_red("standard commitment without a status", "needs 'status: in place|required|planned'",
          lambda: write(".memory/10-product.md", read(".memory/10-product.md").replace(", status: required", "")))
check_red("standard commitment without a module", "standard commitment STD-02 has no standard rule module",
          append(".memory/10-product.md", "- **STD-02** The company holds an ISO/IEC 27001 certificate for the backend. (source: product owner, 2026-10-21, status: in place)\n"))
check_red("standard module naming an undefined commitment", "names commitment STD-09",
          lambda: write("ai_rules/rules/standard-eu-accessibility.md", read("ai_rules/rules/standard-eu-accessibility.md").replace("STD-01", "STD-09")))
check_red("decision overrides a standard rule", "cannot override EUACC-01",
          append(".memory/60-decisions.md", "- **DEC-003** Ship the new checkout screen before its screen reader labels are done. (source: tech lead, 2026-10-21, overrides EUACC-01)\n"))
check_red("ledger anchored to a memory rule that does not exist", "must anchor to a rule ID defined in .memory/10-product.md",
          mutate_receipt=lambda v: v["policy_coverage"][0].update(rule_path=".memory/10-product.md", rule_anchor="Never show a price"))
check_red("generated output listed as policy", "policy source is a generated output or harness file, not project policy: RULES.md",
          mutate_receipt=lambda v: v["policy_sources"].append({"path": "RULES.md", "sha256": sha("RULES.md"), "requirement_ids": ["X-1"]}))
check_red("missing stack row", "needs a stack row", mutate_receipt=lambda v: v.pop("stack"))

def green(label, mutate_files=None, mutate_receipt=None):
    saved = {rel: (target / rel).read_bytes() for rel in [RECEIPT, "RULES.md", ".memory/60-decisions.md"]}
    try:
        value = copy.deepcopy(receipt)
        if mutate_files:
            mutate_files()
        if mutate_receipt:
            mutate_receipt(value)
        save(value)
        assert "READY:" in run(["bash", str(bind), "--check", str(target)], 0, label)
        print(f"GREEN control observed: {label}")
    finally:
        for rel, data in saved.items():
            (target / rel).write_bytes(data)

def exclude_testing(value):
    drop_module("baseline-testing")(value)
    value["excluded_packs"] = [{"name": "baseline-testing", "reason": "Owner decision: tests are owned by another repository."}]
green("baseline pack excluded with a reason", mutate_receipt=exclude_testing)
green("decision overrides a baseline rule",
      append(".memory/60-decisions.md", "- **DEC-002** Send the user ID with crash reports so support can reach the user. (source: privacy review, 2026-10-21, overrides SEC-04)\n"))
green("ledger anchored to a business rule in the memory bank",
      mutate_receipt=lambda v: v["policy_coverage"][0].update(rule_path=".memory/10-product.md", rule_anchor="BIZ-01"))
green("memory bank prose with ID-like bullets and a coverage note is left alone",
      append(".memory/60-decisions.md", "- **L-2026-10-15-01** applied after review.\n- Coverage IDs: policy-001 were moved.\n"))
green("v1: a pack left out is not an error", mutate_receipt=drop_module("tool-sentry"))
green("v1: schema 4 without a policy ledger", mutate_receipt=lambda v: (v.pop("policy_sources"), v.pop("policy_coverage")))
green("resolved rule conflict", mutate_receipt=lambda v: v.__setitem__("rule_conflicts", [
    {"ids": ["SEC-04", "DEC-001"], "status": "resolved", "winner": "DEC-001", "reason": "Business decision recorded on 2026-10-21."}]))
assert "READY:" in run(["bash", str(bind), "--check", str(target)], 0, "restored GREEN")

# Schema 3 receipts are not asked for layers: the same target with schema 3 and no stack row is READY.
value = copy.deepcopy(receipt)
value["schema_version"] = 3
value.pop("stack")
save(value)
assert "READY:" in run(["bash", str(bind), "--check", str(target)], 0, "schema 3 keeps its meaning")
save(receipt)
print("PASS: schema 3 receipts keep their meaning; schema 4 enforces the rule layers")
print("All rule-layer fixtures passed.")
